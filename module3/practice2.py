# Користувач вводить суму кредиту та термін у роках.
# Виберіть відсоткову ставку за такими умовами:

#       ● Для кредиту до 10 000$ на термін до 3 років – ставка 8%
#       
#       ● Для кредиту до 10 000$ на термін понад 3 роки – ставка 10%
# 
#       ● Для кредиту від 10 001$ до 50 000$ на термін до 3 років – ставка 12%
# 
#       ● Для кредиту від 10 001$ до 50 000$ на термін понад 3 роки – ставка 14%
# 
#       ● Для кредиту від 50 000$ на будь-який термін – ставка 20%

# Виведіть відсоткову ставку, загальну суму кредиту та
# щомісячний платіж

credit_summ = float(input("Введіть суму кредиту: "))
term = int(input("Введіть термін кредиту у роках: "))

if credit_summ <= 10000 and term <= 3:
    percent = 8
elif credit_summ <= 10000 and term > 3:
    percent = 10
elif 10000 < credit_summ <= 50000 and term <= 3:
    percent = 12
elif 10000 < credit_summ <= 50000 and term > 3:
    percent = 14
else:
    percent = 20

total = credit_summ * (1 + percent / 100) ** term
month = term * 12
month_payment = total / month

print(f"\nВідсоткова ставка - {percent}% ")
print(f"Загальна сума кредита - {total:.2f} $")
print(f"Щомісячний платіж - {month_payment:.2f} $")

