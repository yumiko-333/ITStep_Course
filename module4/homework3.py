# Завдання 2

# Проводиться опитування «Чи потрібно будувати більше
# дитячих садків у вашому місті?»

# Напишіть програму для підрахунку відповідей.
# Користувач вводить слова «так» або «ні» поки не введе
# слово «стоп», після чого треба показати кількості «так» та
# «ні» і також яких голосів більше.

# Якщо введено невідоме слово, то вивести повідомлення
# про помилку та продовжити підрахунок

count_yes = 0
count_no = 0

while True:
    gardens = input("Чи потрібно будувати більше дитячих садків у вашому місті? (так, ні, стоп) ")

    if gardens == "так":
        count_yes += 1
    
    elif gardens == "ні":
        count_no += 1

    elif gardens != "стоп":
        print("Невідоме слово")

    if gardens == "стоп":
        break

print(f"\nГолосів так -- {count_yes} ")
print(f"Голосів ні -- {count_no}")

if count_no > count_yes:
    print("Голосів 'ні' більше..")
else:
    print("Голосів 'так' більше")

