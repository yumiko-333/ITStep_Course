# Напишіть простий калькулятор
# Користувач вводить два числа після чого обирає яку дію
# виконати:

# 1. сума
# 2. різниця
# 3. добуток
# 4. частка
# 5. вихід

# Якщо користувач обрав частку, то переконайтесь що не
# буде ділення на 0. У випадку проблеми виведіть відповідне
# повідомлення.

while True:
    number1 =  float(input("Введіть перше число: "))
    number2 =  float(input("Введіть друге число: "))

    print("\n1. сума")
    print("2. різниця")
    print("3. добуток")
    print("4. частка")
    print("5. вихід")

    choise = int(input("\nВиберіть опцію: "))

    if choise == 1:
        result = number1 + number2
        symbol = "+"

    elif choise == 2:
        result = number1 - number2
        symbol = "-"

    elif choise == 3:
        result = number1 * number2
        symbol = "*"

    elif choise == 4:
        if number1 == 0 or number2 == 0:
            print("Не правильна умова, виберіть другі числа!")
            continue
        
        result = number1 / number2
        symbol = "/"

    elif choise == 5:
        print("Програма закінчена!")
        break

    print(f"{number1} {symbol} {number2} = {result}")
    print()

