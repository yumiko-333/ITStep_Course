# саму літеру(регістр не важливий)

words = " "

while True:
    word = input("\nВведіть своє слово (END для завершення): ")

    if word.upper() == "END":
        print("Завершення програми...")
        break

    if word[0].upper() == word[-1].upper():
        words += word + ", "

print(
    f"\nСлова які починаються та закінчуються на ту саму літеру \\/\\/\\/ \n\t{words}"
)
