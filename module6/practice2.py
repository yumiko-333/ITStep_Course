# Завдання 10
#
# Користувач вводить математичний вираз, наприклад
# 23+45. Виведіть результат
#   Обробіть такі математичні операції – +*/-
#
# Реалізуйте як консольну програму(закінчити якщо
# введено EXIT)

while True:
    expression = input("\nВведіть математичний вираз: ")

    if expression.upper() == "EXIT":
        print("Программу завершено!")

        break

    if "-" in expression:
        position = expression.find("-")

        number1 = int(expression[:position])
        number2 = int(expression[position + 1 :])

        total = number1 - number2

        print(f"Результат: {total}")

    elif "+" in expression:
        position = expression.find("+")

        number1 = int(expression[:position])
        number2 = int(expression[position + 1 :])

        total = number1 + number2

        print(f"Результат: {total}")

    elif "*" in expression:
        position = expression.find("*")

        number1 = int(expression[:position])
        number2 = int(expression[position + 1 :])

        total = number1 * number2

        print(f"Результат: {total}")

    elif "/" in expression:
        position = expression.find("/")

        number1 = int(expression[:position])
        number2 = int(expression[position + 1 :])

        total = number1 / number2

        print(f"Результат: {total}")
