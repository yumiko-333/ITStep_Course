while True:
    print("Виберіть опцію з меню")
    option = int(input("\n1. Вибрати піццу \n2. Вихід \nВаш вибір: "))

    if option == 1:
        pizza = input("Яку піццу бажаєте? ")
        amount = int(input("Скільки штук? "))

        print(f"Замовлено піццу {pizza} {amount} шт")

    if option == 2:
        break
